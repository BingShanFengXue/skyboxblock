package dev.yg.skyboxblock.client;

import com.mojang.blaze3d.vertex.MeshData;
import com.mojang.blaze3d.vertex.VertexFormat;
import com.mojang.blaze3d.vertex.VertexFormatElement;
import net.minecraft.client.renderer.ShaderInstance;
import org.lwjgl.BufferUtils;
import org.lwjgl.opengl.GL11;
import org.lwjgl.opengl.GL15;
import org.lwjgl.opengl.GL20;
import org.lwjgl.opengl.GL30;

import java.nio.IntBuffer;

/** Project-owned buffers for the game's cloud mesh; no world/batched VertexBuffer upload hooks.
 * Copyright (c) 2026 Bing6512. Distributed under the project MIT license.
 * Coordinates and colors remain exactly as generated by the runtime game method.
 */
final class SkyCloudMesh implements AutoCloseable {
    private int vao,vbo,ebo,indexCount,indexType;
    private VertexFormat format;
    private IntBuffer indices;

    void upload(MeshData mesh) {
        try (mesh) {
            var draw=mesh.drawState();
            if (draw.mode()!=VertexFormat.Mode.QUADS || draw.vertexCount()%4!=0)
                throw new IllegalArgumentException("Native cloud mesh is not a quad list");
            format=draw.format();
            for (var element:new VertexFormatElement[]{VertexFormatElement.POSITION,VertexFormatElement.UV0,VertexFormatElement.COLOR})
                if (!format.contains(element)) throw new IllegalArgumentException("Native cloud mesh lacks "+element);
            if (vao==0) { vao=GL30.glGenVertexArrays(); vbo=GL15.glGenBuffers(); ebo=GL15.glGenBuffers(); }
            bind();
            GL15.glBindBuffer(GL15.GL_ARRAY_BUFFER,vbo);
            GL15.glBufferData(GL15.GL_ARRAY_BUFFER,mesh.vertexBuffer(),GL15.GL_STATIC_DRAW);
            GL15.glBindBuffer(GL15.GL_ELEMENT_ARRAY_BUFFER,ebo);
            indexCount=draw.indexCount();
            var explicit=mesh.indexBuffer();
            if (explicit!=null) {
                indexType=draw.indexType().asGLType;
                GL15.glBufferData(GL15.GL_ELEMENT_ARRAY_BUFFER,explicit,GL15.GL_STATIC_DRAW);
            } else {
                if (indexCount!=draw.vertexCount()/4*6)
                    throw new IllegalArgumentException("Native cloud mesh has inconsistent quad indices");
                if (indices==null || indices.capacity()<indexCount)
                    indices=BufferUtils.createIntBuffer(Math.max(1024,Integer.highestOneBit(indexCount-1)<<1));
                indices.clear();
                for (int base=0;base<draw.vertexCount();base+=4)
                    indices.put(base).put(base+1).put(base+2).put(base+2).put(base+3).put(base);
                indices.flip(); indexType=GL11.GL_UNSIGNED_INT;
                GL15.glBufferData(GL15.GL_ELEMENT_ARRAY_BUFFER,indices,GL15.GL_STATIC_DRAW);
            }
        }
    }

    void bind() { GL30.glBindVertexArray(vao); }

    void prepareDraw(ShaderInstance shader) {
        bind();
        GL15.glBindBuffer(GL15.GL_ARRAY_BUFFER,vbo);
        GL15.glBindBuffer(GL15.GL_ELEMENT_ARRAY_BUFFER,ebo);
        attribute(shader,"Position",VertexFormatElement.POSITION,3,GL11.GL_FLOAT,false);
        attribute(shader,"UV0",VertexFormatElement.UV0,2,GL11.GL_FLOAT,false);
        attribute(shader,"Color",VertexFormatElement.COLOR,4,GL11.GL_UNSIGNED_BYTE,true);
        if (format.contains(VertexFormatElement.NORMAL))
            attribute(shader,"Normal",VertexFormatElement.NORMAL,3,GL11.GL_BYTE,true);
    }

    void draw() { GL11.glDrawElements(GL11.GL_TRIANGLES,indexCount,indexType,0L); }

    private void attribute(ShaderInstance shader,String name,VertexFormatElement element,int size,int type,boolean normalized) {
        int location=GL20.glGetAttribLocation(shader.getId(),name);
        if (location<0) return;
        GL20.glEnableVertexAttribArray(location);
        GL20.glVertexAttribPointer(location,size,type,normalized,format.getVertexSize(),format.getOffset(element));
    }

    int vao() { return vao; }
    int vbo() { return vbo; }
    int ebo() { return ebo; }

    @Override public void close() {
        if (vao!=0) GL30.glDeleteVertexArrays(vao);
        if (vbo!=0) GL15.glDeleteBuffers(vbo);
        if (ebo!=0) GL15.glDeleteBuffers(ebo);
        vao=vbo=ebo=0; indices=null;
    }
}
